"""Process environment/launch flags are read without exposing raw credentials."""
import ast
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('capture_effective',ROOT/'ops/config/capture_effective.py')
capture_module=importlib.util.module_from_spec(spec)
spec.loader.exec_module(capture_module)
schema_spec=importlib.util.spec_from_file_location('configuration_contract',ROOT/'manager/server/configcontract.py')
validator=importlib.util.module_from_spec(schema_spec)
schema_spec.loader.exec_module(validator)


class CaptureContractTest(unittest.TestCase):
    def test_actual_process_environment_and_flags_override_guessed_comments(self):
        with tempfile.TemporaryDirectory() as folder:
            root=Path(folder); proc=root/'123';proc.mkdir()
            (proc/'stat').write_text('123 (own fixture) '+' '.join(['S']+['0']*18+['123456']))
            (proc/'environ').write_bytes(b'WB_GATEWAY_RATE_PER_MIN=600\0WB2API_KEY=private-key-sentinel\0')
            (proc/'cmdline').write_bytes(b'\0'.join([b'python',b'-m',b'server.serve',b'--port',b'7864',
                b'--timeout-graceful-shutdown',b'650',b'--private-token',b'never-echo'])+b'\0')
            unit=root/'gateway.service';unit.write_text('[Service]\nEnvironment=WB_GATEWAY_RATE_PER_MIN=300\n')
            dropin=root/'override with spaces.conf';dropin.write_text('[Service]\nEnvironment=WB_GATEWAY_RATE_PER_MIN=600\n')
            properties={'MainPID':'123','ActiveState':'active','SubState':'running',
                'FragmentPath':str(unit),'DropInPaths':'"'+str(dropin)+'"','EnvironmentFiles':''}
            result=capture_module.capture(properties,root,validator.validate_environment)
            self.assertEqual(result['configuration']['settings']['WB_GATEWAY_RATE_PER_MIN']['value'],600)
            self.assertEqual([row['path'] for row in result['ordered_unit_sources']],[str(unit),str(dropin)])
            self.assertEqual(result['launch_flags']['--port'],'7864')
            self.assertNotIn('private-key-sentinel',json.dumps(result))
            self.assertNotIn('never-echo',json.dumps(result))

    def test_inactive_service_is_not_presented_as_verified(self):
        with self.assertRaises(ValueError):
            capture_module.capture({'MainPID':'0'},'/unused',validator.validate_environment)

    def test_generated_runtime_copies_are_exactly_the_reviewed_implementation(self):
        core=(ROOT/'tools/config_contract_core.py').read_text(encoding='utf-8')
        expected='# Generated by tools/build_config_contracts.py; edit tools/config_contract_core.py.\n'+core
        # QTG moved into Manager. Its portable runtime remains an exact copy;
        # Manager deliberately also owns the four-source drift diagnostics.
        self.assertEqual((ROOT/'manager/server/qtgcore/configcontract.py').read_text(encoding='utf-8'),expected)
        manager=ast.parse((ROOT/'manager/server/configcontract.py').read_text(encoding='utf-8'))
        portable=ast.parse(core)
        definitions={node.name:node for node in manager.body
                     if isinstance(node,(ast.FunctionDef,ast.ClassDef))}
        timezone_guard=ast.dump(ast.parse("spec.get('format') == 'iana_timezone'",mode='eval').body)
        for node in portable.body:
            if not isinstance(node,(ast.FunctionDef,ast.ClassDef)):
                continue
            if node.name=='_parse':
                # The one explicit dialect difference is QTG's IANA timezone
                # validator. Manager has no such setting; introducing one must
                # update its validator instead of silently accepting it.
                schema=json.loads((ROOT/'manager/server/config-schema.json').read_text(encoding='utf-8'))
                self.assertFalse(any(spec.get('format')=='iana_timezone' for spec in schema['settings'].values()))
                node.body=[statement for statement in node.body
                           if not (isinstance(statement,ast.If)
                                   and ast.dump(statement.test)==timezone_guard)]
            self.assertIn(node.name,definitions)
            self.assertEqual(ast.dump(definitions[node.name]),ast.dump(node),node.name)
        for extension in ('parse_source_defaults','compare_sources','redact_value','cross_checks'):
            self.assertIn(extension,definitions)
